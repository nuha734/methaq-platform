# =========================================================

def extract_page_data(html, base_url):

    soup = BeautifulSoup(
        html,
        "html.parser"
    )

    for tag in soup(
        [
            "script",
            "style",
            "noscript",
            "svg",
        ]
    ):
        tag.decompose()

    text = soup.get_text(
        " ",
        strip=True
    )

    links = []

    for a in soup.find_all(
        "a",
        href=True
    ):

        label = a.get_text(
            " ",
            strip=True
        )

        href = urljoin(
            base_url,
            a["href"]
        )

        links.append({
            "label": label,
            "url": href,
        })

    return text, links


