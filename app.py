def privacy_score(results):

    if not results:
        return 0

    values = []

    for result in results:

        if result["status"] == "🟢":
            values.append(1)

        elif result["status"] == "🟡":
            values.append(0.5)

        else:
            values.append(0)

    return round(
        sum(values)
        / len(values)
        * 100
    )


def store_score(results):

    if not results:
        return 0

    values = []

    for result in results:

        if result["status"] == "🟢":
            values.append(1)

        else:
            values.append(0)

    return round(
        sum(values)
        / len(values)
        * 100
    )


