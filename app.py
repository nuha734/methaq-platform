def analyze_privacy(text):

    results = []

    sentences = split_sentences(text)

    for rule in PRIVACY_RULES:

        rule_name = rule["name"]
        patterns = rule["patterns"]

        # -------------------------------------------------
        # مدة الاحتفاظ لها منطق خاص
        # -------------------------------------------------

        if rule.get("special") == "retention":

            retention_evidence = None

            for sentence in sentences:

                normalized = normalize_text(sentence)

                # يجب أن تحتوي الجملة على مؤشر للاحتفاظ
                has_retention = any(
                    x in normalized
                    for x in [
                        "احتفاظ",
                        "نحتفظ",
                        "يتم الاحتفاظ",
                        "نحتفظ ببيانات",
                        "حفظ البيانات",
                    ]
                )

                # ويجب أن تحتوي على مدة/فترة/زمن
                has_duration = any(
                    x in normalized
                    for x in [
                        "مدة",
                        "فترة",
                        "لمدة",
                        "للمدة",
                        "يوم",
                        "يوما",
                        "يومًا",
                        "شهر",
                        "اشهر",
                        "أشهر",
                        "سنة",
                        "سنوات",
                        "عام",
                        "اعوام",
                        "أعوام",
                        "حتى انتهاء",
                        "حتى تحقيق",
                        "للمدة اللازمة",
                    ]
                )

                if has_retention and has_duration:

                    retention_evidence = sentence
                    break

                # دعم المدد الرقمية إذا كانت مرتبطة بسياق البيانات
                if (
                    re.search(r"\b\d+\s*(يوم|يوما|يومًا|شهر|سنة|عام|سنوات)\b", normalized)
                    and (
                        "بيانات" in normalized
                        or "معلومات" in normalized
                        or "نحتفظ" in normalized
                        or "احتفاظ" in normalized
                    )
                ):
                    retention_evidence = sentence
                    break

            if retention_evidence:

                results.append({
                    "name": rule_name,
                    "status": "🟢",
                    "evidence": retention_evidence,
                })

            else:

                results.append({
                    "name": rule_name,
                    "status": "🔴",
                    "evidence": None,
                })

            continue

        # -------------------------------------------------
        # باقي المتطلبات
        # -------------------------------------------------

        matched_sentences = []

        for sentence in sentences:

            normalized_sentence = normalize_text(
                sentence
            )

            matched = [
                pattern
                for pattern in patterns
                if normalize_text(pattern)
                in normalized_sentence
            ]

            if matched:
                matched_sentences.append(
                    (
                        sentence,
                        matched
                    )
                )

        # عدد المؤشرات المختلفة
        unique_matches = set()

        for _, matches in matched_sentences:
            for match in matches:
                unique_matches.add(
                    normalize_text(match)
                )

        # -------------------------------------------------
        # تحديد الحالة
        #
        # جملة واحدة فيها أكثر من مؤشر مرتبط = 🟢
        # مؤشر واحد فقط = 🟡
        # لا يوجد = 🔴
        # -------------------------------------------------

        if matched_sentences:

            if len(unique_matches) >= 2:
                status = "🟢"

            else:
                status = "🟡"

            evidence = matched_sentences[0][0]

        else:

            status = "🔴"
            evidence = None

        results.append({
            "name": rule_name,
            "status": status,
            "evidence": evidence,
        })

    return results


